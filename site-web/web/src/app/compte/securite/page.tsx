'use client';

import { useCallback, useEffect, useState } from 'react';
import { useRouter } from 'next/navigation';
import QRCode from 'qrcode';
import { CodeInput, Notice, Submit, TextLink } from '@/components/auth-ui';
import { useMember } from '@/lib/auth';
import { supabase } from '@/lib/supabase';
import { useLang } from '@/lib/lang-client';

/** Vérification en 2 étapes (TOTP maison de l'app : mfa_totp_enroll / confirm / disable). */
export default function Securite() {
  const { ready, session, member } = useMember();
  const { tr } = useLang();
  const router = useRouter();
  const [enabled, setEnabled] = useState<boolean | null>(null);
  const [enroll, setEnroll] = useState<{ qr: string; secret: string } | null>(null);
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);
  const [msg, setMsg] = useState<{ tone: 'error' | 'success' | 'info'; text: string } | null>(null);

  const load = useCallback(async () => {
    const { data } = await supabase.rpc('mfa_totp_status');
    setEnabled(!!(data as { enabled?: boolean })?.enabled);
  }, []);
  useEffect(() => {
    if (ready && !session) router.replace('/connexion?suite=/compte/securite');
    else if (session) load();
  }, [ready, session, router, load]);
  if (!member) return <div className="min-h-screen" />;

  const start = async () => {
    setBusy(true);
    setMsg(null);
    const { data, error } = await supabase.rpc('mfa_totp_enroll');
    setBusy(false);
    if (error || !data) return setMsg({ tone: 'error', text: tr("L'activation n'a pas pu démarrer. Réessaie.", 'Activation could not start. Try again.') });
    const d = data as { otpauth_uri: string; secret_base32: string };
    setEnroll({ qr: await QRCode.toDataURL(d.otpauth_uri, { margin: 1, width: 240, color: { dark: '#070504', light: '#fff4e0' } }), secret: d.secret_base32 });
  };
  const confirm = async (e: React.FormEvent) => {
    e.preventDefault();
    setBusy(true);
    const { data, error } = await supabase.rpc('mfa_totp_confirm', { p_code: code });
    setBusy(false);
    if (error || !(data as { ok?: boolean })?.ok) return setMsg({ tone: 'error', text: tr('Code incorrect. Vérifie l’heure de ton téléphone et réessaie.', "Incorrect code. Check your phone's time and try again.") });
    setEnroll(null);
    setCode('');
    setEnabled(true);
    setMsg({ tone: 'success', text: tr('Vérification en 2 étapes activée.', '2-step verification enabled.') });
  };
  const disable = async () => {
    if (!window.confirm(tr('Désactiver la vérification en 2 étapes ? Ton compte sera moins protégé.', 'Turn off 2-step verification? Your account will be less protected.'))) return;
    setBusy(true);
    const { error } = await supabase.rpc('mfa_totp_disable');
    setBusy(false);
    if (error) return setMsg({ tone: 'error', text: tr("La désactivation n'a pas abouti.", 'Turning it off failed.') });
    setEnabled(false);
    setMsg({ tone: 'info', text: tr('Vérification en 2 étapes désactivée.', '2-step verification turned off.') });
  };

  return (
    <div className="mx-auto max-w-xl px-5 pb-16 pt-32">
      <TextLink href="/compte">‹ {tr('Mon compte', 'My account')}</TextLink>
      <h1 className="text-gold-gradient mt-4 font-display text-4xl font-black">{tr('Vérification en 2 étapes', '2-step verification')}</h1>
      <p className="mt-3 text-body">{tr("Un code temporaire, généré par une application d'authentification (Google Authenticator, Authy…), en plus de ton mot de passe.", 'A temporary code, generated by an authenticator app (Google Authenticator, Authy…), on top of your password.')}</p>
      <div className="mt-8 space-y-6">
        {msg && <Notice tone={msg.tone}>{msg.text}</Notice>}
        {enabled === true && !enroll && (
          <div className="rounded-3xl bg-free/10 p-6 ring-1 ring-free/30">
            <p className="font-bold text-free">{tr('Activée', 'Enabled')}</p>
            <p className="mt-1 text-sm text-body">{tr('Ton compte demande un code à chaque nouvelle connexion.', 'Your account asks for a code at every new sign-in.')}</p>
            <button onClick={disable} disabled={busy} className="mt-4 text-sm font-semibold text-terra hover:underline">
              {tr('Désactiver', 'Turn off')}
            </button>
          </div>
        )}
        {enabled === false && !enroll && (
          <button onClick={start} disabled={busy} className="w-full rounded-full bg-gold py-4 font-extrabold text-ink">
            {busy ? tr('Un instant…', 'One moment…') : tr('Activer la vérification en 2 étapes', 'Turn on 2-step verification')}
          </button>
        )}
        {enroll && (
          <form onSubmit={confirm} className="space-y-6">
            <p className="font-bold text-ivory">{tr("1. Scanne ce code avec ton application d'authentification", '1. Scan this code with your authenticator app')}</p>
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={enroll.qr} alt={tr('QR code de vérification', 'Verification QR code')} className="mx-auto h-60 w-60 rounded-2xl" />
            <p className="text-center text-sm text-body">
              {tr('Ou saisis ce code :', 'Or enter this code:')} <code className="break-all font-bold text-gold">{enroll.secret}</code>
            </p>
            <p className="font-bold text-ivory">{tr('2. Entre le code à 6 chiffres affiché', '2. Enter the 6-digit code shown')}</p>
            <CodeInput value={code} onChange={setCode} />
            <Submit busy={busy} disabled={code.length !== 6}>
              {tr('Confirmer', 'Confirm')}
            </Submit>
          </form>
        )}
      </div>
    </div>
  );
}

