-- AFROBACK Back-office — module Traduction (lot 2)
-- Généré le 2026-08-12, à exécuter dans le SQL Editor du dashboard Supabase.
--
-- Contexte : contrairement à Découverte/Mythologie/École des Héros, aucune
-- table n'existait pour suivre l'avancement de la traduction des 4 langues
-- camerounaises (ewondo, douala, bassa, bamiléké) clé par clé. Le vrai
-- travail de traduction continue de se faire ailleurs (base de connaissances
-- livrables/sites-web/afroback/Langues/ewondo-connaissances.md pour
-- l'éwondo, recherche de dictionnaires pour les autres) : cette table sert
-- UNIQUEMENT à visualiser l'avancement réel dans le back-office, elle ne
-- remplace pas ce travail éditorial.
--
-- Statut à 3 états, jamais inventé : 'vide' (rien), 'brouillon' (une valeur
-- existe dans le code DICT.<langue> mais n'a jamais été relue par un
-- locuteur natif), 'valide' (relu et validé par un locuteur natif — AUCUNE
-- ligne n'a ce statut à ce jour, personne ne l'a mis à ce niveau). Le seed
-- ci-dessous reflète l'état RÉEL du code au 2026-08-12 (site/index.html,
-- objet DICT) : 160 lignes (40 clés × 4 langues), dont seulement 2 en
-- 'brouillon' (douala : navDecouvrir, footerLangs — voir
-- context/AFROBACK.md, décision du 2026-07-21). Toutes les autres valent
-- 'vide'. Si les clés du site évoluent, ce seed devra être régénéré (pas de
-- script automatique pour l'instant, à la main comme le reste du contenu
-- back-office non lié à heros/decouverte/mythes).

create extension if not exists pgcrypto;

create table if not exists public.translation_entries (
  id uuid primary key default gen_random_uuid(),
  cle text not null,
  langue text not null check (langue in ('ewo', 'dua', 'bas', 'bam')),
  source_fr text not null,
  brouillon text,
  statut text not null default 'vide' check (statut in ('vide', 'brouillon', 'valide')),
  updated_at timestamptz not null default now(),
  unique (cle, langue)
);

alter table public.translation_entries enable row level security;
-- Aucune policy : comme admin_users/admin_activity_log (schema-admin-heros.sql),
-- lecture/écriture réservées à service_role — jamais anon/authenticated.

